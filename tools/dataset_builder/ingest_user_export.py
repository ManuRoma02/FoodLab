"""Ingestion Agent for FoodLab User-Exported Custom & Scanned Foods.

Parses JSON exports generated by the FoodLab Android app (Settings -> Esporta Cibi Creati),
validates macros through the Mandatory Macro Gate, and merges them into the SQLite Master database.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
import sqlite3
from typing import List, Tuple

from tools.dataset_builder.models import FoodRecord, PortionRecord
from tools.dataset_builder.validator import validate_and_normalize

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

def parse_user_export(json_path: str) -> Tuple[List[FoodRecord], List[PortionRecord]]:
    path = Path(json_path)
    if not path.exists():
        logger.error(f"Export file not found: {json_path}")
        return [], []

    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, list):
        logger.error("Invalid export format: expected a JSON list of food items.")
        return [], []

    foods: List[FoodRecord] = []
    portions: List[PortionRecord] = []

    for item in data:
        if not isinstance(item, dict):
            continue

        raw_dict = {
            "barcode": item.get("barcode", ""),
            "name": item.get("name", ""),
            "brand": item.get("brand", "User Created"),
            "category": "Alimenti Personalizzati Utente",
            "calories_100g": item.get("caloriesPer100g", item.get("calories_100g")),
            "protein_100g": item.get("proteinPer100g", item.get("protein_100g")),
            "carbs_100g": item.get("carbsPer100g", item.get("carbs_100g")),
            "fat_100g": item.get("fatPer100g", item.get("fat_100g")),
            "default_serving_size": item.get("defaultServingSize", 100)
        }

        food_rec = validate_and_normalize(raw_dict, source="USER_EXPORT")
        if food_rec:
            foods.append(food_rec)
            raw_portions = item.get("portions", [])
            for p in raw_portions:
                p_name = p.get("name")
                p_weight = p.get("weightGrams", p.get("weight_grams"))
                if p_name and p_weight and float(p_weight) > 0:
                    portions.append(PortionRecord(
                        food_barcode_or_key=food_rec.barcode or food_rec.name,
                        name=str(p_name),
                        weight_grams=float(p_weight)
                    ))

    return foods, portions

def merge_user_foods_into_db(db_path: str, foods: List[FoodRecord], portions: List[PortionRecord]) -> int:
    if not foods:
        logger.info("No valid foods to ingest.")
        return 0

    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()

    inserted_count = 0
    for food in foods:
        # Check if already exists by barcode or identical name and brand
        if food.barcode:
            cursor.execute("SELECT id FROM foods WHERE barcode = ?", (food.barcode,))
        else:
            cursor.execute("SELECT id FROM foods WHERE name = ? AND brand = ?", (food.name, food.brand))

        existing = cursor.fetchone()
        if existing:
            food_id = existing[0]
        else:
            cursor.execute("""
                INSERT INTO foods (name, brand, category, barcode, calories_100g, protein_100g, carbs_100g, fat_100g, default_serving_size, source)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                food.name, food.brand, food.category, food.barcode,
                food.calories_100g, food.protein_100g, food.carbs_100g, food.fat_100g,
                food.default_serving_size, food.source
            ))
            food_id = cursor.lastrowid
            inserted_count += 1

        # Link portions for this food
        for p in portions:
            if p.food_barcode_or_key in (food.barcode, food.name):
                cursor.execute("""
                    INSERT OR IGNORE INTO food_portions (food_id, name, weight_grams)
                    VALUES (?, ?, ?)
                """, (food_id, p.name, p.weight_grams))

    conn.commit()
    conn.close()
    logger.info(f"Ingested {inserted_count} new foods and associated portions into {db_path}!")
    return inserted_count

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Ingest user-exported foods into FoodLab master database")
    parser.add_argument("export_json", help="Path to exported foodlab_user_foods.json")
    parser.add_argument("--db-path", default="tools/dataset_builder/foodlab_italian_master.db", help="Path to master SQLite DB")
    args = parser.parse_args()

    f_list, p_list = parse_user_export(args.export_json)
    logger.info(f"Parsed {len(f_list)} valid foods and {len(p_list)} portions from {args.export_json}.")
    merge_user_foods_into_db(args.db_path, f_list, p_list)
