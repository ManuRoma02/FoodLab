def extract_chains_foods(
    custom_json_path: Optional[Union[str, Path]] = None, limit: Optional[int] = None
) -> Tuple[List[FoodRecord], List[PortionRecord]]:
    """
    Extract verified Italian Fast Food & Restaurant Chain items and linked portion records.
    Optionally reads from custom JSON or uses canonical built-in database.
    """
    items_raw = list(CANONICAL_ITALIAN_CHAINS)

    if custom_json_path:
        p = Path(custom_json_path)
        if p.exists():
            with open(p, "r", encoding="utf-8") as f:
                data = json.load(f)
                custom_list = (
                    data
                    if isinstance(data, list)
                    else data.get("foods") or data.get("items") or []
                )
                items_raw.extend(custom_list)

    foods: List[FoodRecord] = []
    portions: List[PortionRecord] = []

    for item in items_raw:
        if not isinstance(item, dict):
            continue

        food = validate_and_normalize(item, source="CHAINS_IT")
        if not food:
            continue

        foods.append(food)

        # Linked portion
        p_name = str(item.get("portion_name") or f"Porzione 100g").strip()
        p_weight = float(item.get("portion_weight") or item.get("default_serving_size") or 100.0)
        portions.append(
            PortionRecord(
                food_barcode_or_key=food.barcode if food.barcode else food.name,
                name=p_name,
                weight_grams=p_weight,
            )
        )

        if limit and len(foods) >= limit:
            break

    return foods, portions
